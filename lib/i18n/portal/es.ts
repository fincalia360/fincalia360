/** Mismo formato que el español, con textos libres (cada idioma pone los suyos). */
type Widen<T> = T extends (...args: infer A) => unknown
  ? (...args: A) => string
  : T extends readonly string[]
    ? string[]
    : T extends string
      ? string
      : { [K in keyof T]: Widen<T[K]> };
export type PortalDict = Widen<typeof es>;

export default es as PortalDict;
